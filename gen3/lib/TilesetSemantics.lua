function S.pair(def,cache)
 local pair=def and def.pair;local expected=def and maps[def.id or def.name]
 if not expected or pair~=expected then return pair end
 local spec=pairs[pair];local verified=S.verified[pair]
 if verified==nil then
  local chunks={};for _,file in ipairs{'tiles.4bpp','metatiles.bin','attributes.bin','palettes.bin'}do
   local raw=cache:read('data/generated/gba/map_tree/tilesets/'..spec.source..'/'..file)
   if not raw then S.verified[pair]=false;return pair end
   chunks[#chunks+1]=raw
  end
  verified=love.data.encode('string','hex',love.data.hash('sha256',table.concat(chunks)))==spec.sha256
  S.verified[pair]=verified
 end
 return verified and spec.canonical or pair
end
function S.atlasPair(ts)
 local pair=ts and ts.pair;local spec=pairs[pair]
 return spec and S.verified[pair] and spec.canonical or pair
end
