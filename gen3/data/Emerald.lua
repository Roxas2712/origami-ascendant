function E.isSupported(id,def)
 -- Native outdoor headers share the Hoenn surface renderer. A preview list
 -- must never silently drop a city/route back to the flat engine view.
 local outdoor=def and (def.id or def.name)==id and tostring(id):match('^EM_')
  and (tonumber(def.mapType)==1 or tonumber(def.mapType)==2 or tonumber(def.mapType)==3 or tonumber(def.mapType)==6)
 local base=E.secretBaseRooms[id]
 local secret=base and def and tonumber(def.mapType)==9 and def.pair==base.pair
 return secret==true or outdoor==true or E.supported[id]==true or E.publicRooms[id]~=nil or E.homeRooms[id]~=nil
end
